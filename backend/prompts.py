DUO_HANDOFF = """\
今は{partner}さんと2人で交互に話しています。直前の{partner}さんの発言を受けて、
あなた（{me}）が続きを話す番です。相手の話に軽く反応してから、自分の視点で話を進めて
ください。相手の名前を毎回呼びかける必要はありません。
"""


def covered_block(covered: list[str]) -> str:
    if not covered:
        return "（まだ何も話していません）"
    return "\n".join(f"- {c}" for c in covered[-12:])
